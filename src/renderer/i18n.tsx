const DICTS: Record<Locale, Dict> = { ru: RU, en: EN };

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string) => string;
};

const I18nContext = createContext<I18nContextValue>({
  locale: 'ru',
  setLocale: () => {},
  t: (key) => RU[key] || key,
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>('ru');

  useEffect(() => {
    (window as any).api.getSetting('ui.locale', 'ru').then((value: string) => {
      setLocaleState(value === 'en' ? 'en' : 'ru');
    }).catch(() => {});
  }, []);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    (window as any).api.setSetting('ui.locale', next);
    document.documentElement.lang = next;
  }, []);

  useEffect(() => { document.documentElement.lang = locale; }, [locale]);

  const t = useCallback((key: string) => DICTS[locale][key] || DICTS.ru[key] || key, [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}

