export function normalizeKbRole(role: any): KbRole {
  if (role === 'admin' || role === 'operator') return role;
  return 'user';
}

export function roleLabelRu(role: KbRole) {
  return ({ admin: 'Администратор', user: 'Пользователь', operator: 'Оператор' } as const)[role];
}

